create trigger invoices_assign_number
before insert on public.invoices
for each row execute function public.assign_invoice_number();

create trigger invoices_set_updated_at
before update on public.invoices
for each row execute function public.set_updated_at();

grant select, insert, update, delete on public.quotes to anon, authenticated;
grant all privileges on public.quotes to service_role;
grant select, insert, update, delete on public.invoices to anon, authenticated;
grant all privileges on public.invoices to service_role;

-- po_documents records which RTQ/Quote it was created from, so the PO
-- editor/list can show the chain and so the RTQ picker (in the PO creation
-- form) can tell which RTQs already have a Purchase Order. Nullable: ad-hoc
-- POs created without going through an RTQ keep working unchanged.
alter table public.po_documents
    add column if not exists rtq_number text,
    add column if not exists quote_number text;

create index if not exists po_documents_rtq_number_idx on public.po_documents (rtq_number);
